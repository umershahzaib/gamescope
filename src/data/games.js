export const getGameById = (id) => {
  return gamesData.find(game => game.id === parseInt(id))
}

export const filterGamesByGenre = (genre) => {
  if (genre === "All") return gamesData
  return gamesData.filter(game => game.genre === genre)
}

export const getRecommendedGames = (currentGameId, count = 3) => {
  const currentGame = getGameById(currentGameId)
  if (!currentGame) return gamesData.slice(0, count)

  return gamesData
    .filter(game => game.id !== currentGameId && game.genre === currentGame.genre)
    .slice(0, count)
}
